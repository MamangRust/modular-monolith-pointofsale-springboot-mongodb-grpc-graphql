package com.sanedge.pointofsale.common.outbox;

import java.time.LocalDateTime;

import org.springframework.data.annotation.Id;
import org.springframework.data.mongodb.core.index.CompoundIndex;
import org.springframework.data.mongodb.core.index.Indexed;
import org.springframework.data.mongodb.core.mapping.Document;
import org.springframework.data.mongodb.core.mapping.Field;

import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;

/**
 * Transactional outbox row (shared {@code outbox} collection).
 *
 * <p>All producer modules write the same collection and are distinguished by
 * {@code aggregateType}; the shared {@link OutboxPublisher} drains PENDING rows
 * regardless of owner. Producers persist the business entity and the outbox row
 * in the same request so an email event is never lost when Kafka is briefly
 * unavailable.
 *
 * <p>Unlike the JPA blueprint counterpart, the id is a String generated by
 * {@code MongoStringIdGenerator} (matching the rest of the POS collections).
 */
@Data
@NoArgsConstructor
@AllArgsConstructor
@Document(collection = "outbox")
@CompoundIndex(name = "ix_outbox_status_created", def = "{'status': 1, 'created_at': 1}")
public class Outbox {

    @Id
    @Field("id")
    private String id;

    /** Logical producer, e.g. {@code USER} or {@code MERCHANT}. */
    @Field("aggregate_type")
    private String aggregateType;

    /** Kafka record key. */
    @Field("aggregate_id")
    private String aggregateId;

    @Field("topic")
    private String topic;

    @Field("payload")
    private String payload;

    @Indexed(name = "ix_outbox_status")
    @Field("status")
    private OutboxStatus status = OutboxStatus.PENDING;

    @Field("attempts")
    private Integer attempts = 0;

    @Field("created_at")
    private LocalDateTime createdAt;

    @Field("processed_at")
    private LocalDateTime processedAt;

    @Field("last_error")
    private String lastError;
}
